document.querySelectorAll("[data-brief-form]").forEach((form) => {
  const steps = [...form.querySelectorAll("[data-step]")];
  const backButton = form.querySelector("[data-step-back]");
  const nextButton = form.querySelector("[data-step-next]");
  const submitButton = form.querySelector("[data-step-submit], .button-submit");
  const count = form.querySelector("[data-step-count]");
  const label = form.querySelector("[data-step-label]");
  const progressBar = form.querySelector("[data-progress-bar]");
  const message = form.querySelector(".form-message");
  const fileInput = form.querySelector('input[type="file"]');
  const fileList = form.querySelector("[data-selected-files]");
  let currentStep = 1;

  function currentDictionary() {
    const language = document.documentElement.lang;
    return { ...translations[language], ...briefTranslations[language] };
  }

  function showStep(step) {
    currentStep = step;
    form.dataset.currentStep = String(currentStep);
    const dictionary = currentDictionary();
    steps.forEach((stepElement, index) => {
      stepElement.hidden = index + 1 !== currentStep;
    });
    count.textContent = `${String(currentStep).padStart(2, "0")} / ${String(steps.length).padStart(2, "0")}`;
    label.textContent = dictionary[`formStep${currentStep}Label`];
    progressBar.style.width = `${(currentStep / steps.length) * 100}%`;
    backButton.hidden = currentStep === 1;
    nextButton.hidden = currentStep === steps.length;
    submitButton.hidden = currentStep !== steps.length;
    message.textContent = "";
  }

  function focusCurrentStep() {
    const activeStep = steps[currentStep - 1];
    const heading = activeStep.querySelector("legend");
    heading.setAttribute("tabindex", "-1");
    heading.focus({ preventScroll: true });
    activeStep.scrollIntoView({ behavior: "smooth", block: "start" });
  }

  function validateCurrentStep() {
    const activeStep = steps[currentStep - 1];
    const invalidField = [...activeStep.querySelectorAll("input, select, textarea")]
      .find((field) => !field.checkValidity());
    if (invalidField) {
      invalidField.reportValidity();
      return false;
    }
    return true;
  }

  nextButton.addEventListener("click", () => {
    if (validateCurrentStep()) {
      showStep(Math.min(currentStep + 1, steps.length));
      focusCurrentStep();
    }
  });

  backButton.addEventListener("click", () => {
    showStep(Math.max(currentStep - 1, 1));
    focusCurrentStep();
  });

  fileInput?.addEventListener("change", () => {
    const dictionary = currentDictionary();
    const files = [...fileInput.files];
    const maxFiles = Number(fileInput.dataset.maxFiles);
    const maxSize = Number(fileInput.dataset.maxFileSize);
    let errorKey = "";
    if (files.length > maxFiles) errorKey = "formFilesTooMany";
    else if (files.some((file) => file.size > maxSize)) errorKey = "formFileTooLarge";
    fileInput.setCustomValidity(errorKey ? dictionary[errorKey] : "");
    fileList.textContent = errorKey
      ? dictionary[errorKey]
      : files.length
        ? dictionary.formFilesSelected.replace("{count}", String(files.length))
        : "";
  });

  form.addEventListener("submit", async (event) => {
    event.preventDefault();
    if (currentStep !== steps.length || !validateCurrentStep()) return;
    const endpoint = form.action;

    submitButton.disabled = true;
    message.textContent = "";
    try {
      const response = await fetch(endpoint, {
        method: "POST",
        body: new FormData(form),
        headers: { Accept: "application/json" }
      });
      if (!response.ok) throw new Error(`Form submission failed with status ${response.status}`);
      form.reset();
      fileList.textContent = "";
      showStep(1);
      message.textContent = currentDictionary().formSendSuccess;
    } catch (error) {
      message.textContent = currentDictionary().formSendError;
      console.error("Could not submit the project brief.", error);
    } finally {
      submitButton.disabled = false;
    }
  });

  showStep(currentStep);
});
