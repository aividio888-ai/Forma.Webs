function applyLanguage(language) {
  const selectedLanguage = translations[language] ? language : "uk";
  const dictionary = { ...translations[selectedLanguage], ...briefTranslations[selectedLanguage] };
  document.documentElement.lang = selectedLanguage;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value !== undefined) element.innerHTML = value;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const value = dictionary[element.dataset.i18nPlaceholder];
    if (value !== undefined) element.placeholder = value;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const value = dictionary[element.dataset.i18nAria];
    if (value !== undefined) element.setAttribute("aria-label", value);
  });
  const page = document.body.dataset.page || "home";
  const titles = { home: "pageTitleHome", services: "pageTitleServices", process: "pageTitleProcess" };
  const descriptions = { home: "metaHome", services: "metaServices", process: "metaProcess" };
  document.title = dictionary[titles[page]];
  document.querySelector('meta[name="description"]').content = dictionary[descriptions[page]];
  const briefForm = document.querySelector("[data-brief-form]");
  if (briefForm) {
    const stepLabel = briefForm.querySelector("[data-step-label]");
    const activeStep = Number(briefForm.dataset.currentStep || 1);
    stepLabel.textContent = dictionary[`formStep${activeStep}Label`];
  }
  const selector = document.querySelector("#language");
  if (selector) selector.value = selectedLanguage;
  try {
    localStorage.setItem("forma-language", selectedLanguage);
  } catch (error) {
    console.warn("Could not save the selected language.", error);
  }
}

